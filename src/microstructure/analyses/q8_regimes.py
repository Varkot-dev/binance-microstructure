"""Q8: regime comparator — does the cross-sectional law hold across time?

Phase 4 tests whether the Q4/Q6 cross-sectional findings from a single
month (June 2023, the "baseline") survive in other market regimes. This
module never touches raw data or `data/` — it is a pure downstream
comparator that loads already-computed `q4_cross_section.json` (required)
and `q6_endogeneity.json` (optional — a regime dir may not have a Q6 run
yet, or Q6 may not have been run for that period at all) from a baseline
directory and one or more regime directories, then:

1. **Recomputes** every cross-sectional regression (γ̂ vs log10(activity),
   p_flip vs log10(activity), and α̂_median vs log10(activity) when Q6 is
   present) from the per-symbol records using this module's own numpy OLS
   — the upstream json's stored `regressions` / `activity_regression`
   blocks are never trusted blindly. The recomputed numbers are
   cross-checked against the stored ones and any material mismatch is
   reported as an explicit warning in the output json rather than silently
   overwritten or ignored (a mismatch would mean either this module's OLS
   disagrees with q4/q6's OLS, or the upstream json was hand-edited /
   generated by a different code version — both are worth surfacing).
2. **Cross-regime comparison**: symbol-overlap sets (baseline ∩ each
   regime), survivorship (baseline symbols absent from a regime, split
   into "skipped below min_events" vs "failed/missing" using that
   regime's own q4 `skips`/`failures` lists when available), Spearman
   rank correlation of p_flip / γ / α across each regime pair on the
   overlap (implemented via numpy average-rank ranking — no scipy), and a
   law-stability table: same-sign check on the flip-law slope across all
   regimes, slope ratio vs. baseline, and a γ-invariance verdict (flat in
   every regime iff every regime's γ-vs-activity R² < 0.05).
3. **Outputs**: `q8_regimes.{md,json,png}` — the png has three panels
   (flip-law overlay across regimes, γ-vs-activity overlay across
   regimes, and a symbol-level p_flip baseline-vs-regime scatter with a
   y=x reference line for the first non-baseline regime, if any).

All law-stability verdicts in the md are phrased FROM the recomputed
numbers (f-strings driven by sign/ratio/R² comparisons) — the template
text does not hardcode which conclusion ("law holds" vs "law breaks
down") is correct; either outcome is a valid finding and must read
correctly regardless of what the data says.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

# Regression-mismatch tolerance: recomputed vs. stored slope/intercept/r2
# are flagged as a warning if they differ by more than this absolute
# amount. This is deliberately loose (both sides use the same
# `np.polyfit(..., deg=1)` machinery on the same records, so an exact
# match is expected in the ordinary case) — it exists to catch a real
# discrepancy (different symbol set, stale json, code drift) without
# flagging float-noise-level differences.
REGRESSION_MISMATCH_TOL = 1e-6

# γ-invariance verdict threshold: a regime's γ-vs-activity regression is
# considered "flat" (no detectable activity dependence) when its R² falls
# below this. Matches the informal "R² < 0.05" bar already used in Q4's
# own findings language for a weak/no relationship.
GAMMA_FLAT_R2_THRESHOLD = 0.05

# A flip-law slope counts toward a sign verdict only when it is at least this
# many standard errors from zero. A slope inside that band has no reliable
# sign, so "same sign as the baseline" would carry no information.
FLIP_SLOPE_MIN_SE = 2.0

# Kernel-mode split for Q6's single-exponential Hawkes fits. A fitted decay
# rate above this (1/beta < 0.1 business-time seconds) means the MLE locked
# onto the fast component of a multi-timescale kernel, which captures only
# part of the excitation and so understates alpha. A regime whose fast-mode
# share moves this far from the baseline's has an alpha median that is not
# comparable to the baseline's as a measure of endogeneity.
FAST_MODE_BETA = 10.0
FAST_MODE_SHIFT_FLAG = 0.2


def _chrono_key(label: str) -> tuple:
    """Sort key for a regime label: (YYYY, MM) parsed from a leading YYYY-MM
    prefix, else the label itself (pushed after any parsed labels) so an
    unexpected label format degrades to alphabetical rather than crashing.
    """
    m = re.match(r"^(\d{4})-(\d{2})", label)
    if m:
        return (0, int(m.group(1)), int(m.group(2)), label)
    return (1, 0, 0, label)


