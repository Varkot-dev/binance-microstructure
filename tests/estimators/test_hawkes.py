def test_seasonal_baseline_confound_mimics_long_memory():
    """THE CONFOUND TRAP, sitting deliberately next to the headline
    long-memory test above: a K=1 -> K=2 rise in n̂ with a slow (small
    beta) second component is NOT unique evidence of long-memory
    self-excitation. It is ALSO produced by residual baseline
    non-stationarity that a constant-mu fit cannot represent, per the
    Filimonov & Sornette (2015) regime-switching trap already documented
    on `branching_count_variance` (see
    `test_regime_switching_produces_spurious_endogeneity`) -- this test
    shows the SAME confound also fools the multi-exponential MLE, not just
    the single-exponential MLE or the count-variance estimator.

    Ground truth here is a TRUE single-exponential Hawkes process (n=0.4,
    beta=2.0 -- no long memory whatsoever) with a piecewise-constant ±30%
    baseline wobble on 600s blocks (`np.tile([0.7, 1.3], 72)` over a
    60_000s window = 144 alternating 0.7x/1.3x-mean blocks of 600s/72... in
    `simulate_seasonal_hawkes_exp`'s bin convention this divides the 86400s
    day into 144 bins of 600s each, and t_end=60_000s covers a bit over half
    that period). Despite zero true long memory, K=1 -> K=2 shows
    n̂1=0.46 -> n̂2=0.83 (a jump exceeding 0.2) with a spurious near-zero
    beta component -- numerically indistinguishable in shape from the
    genuine-long-memory signature in
    `test_multiexp_k1_underestimates_planted_two_timescale_kernel` /
    `test_multiexp_k2_recovers_planted_two_timescale_kernel` above. THE
    POINT: n̂(K) sensitivity alone cannot distinguish "the true kernel has
    long memory" from "the baseline is not actually constant" -- per
    `fit_hawkes_multiexp`'s docstring, distinguishing them requires (a)
    checking the slow component's timescale 1/beta_slow against the
    deseasonalization bin width and fit-window length, and (b) the
    block-wise-constant-mu control.
    """
    shape = np.tile([0.7, 1.3], 72)
    t_end = 60_000.0
    times = simulate_seasonal_hawkes_exp(0.5, 0.4, 2.0, t_end, shape, seed=5)

    fit_k1 = fit_hawkes_multiexp(times, t_end, K=1)
    fit_k2 = fit_hawkes_multiexp(times, t_end, K=2)

    assert fit_k2.n - fit_k1.n > 0.2, (
        f"expected the baseline-drift confound to produce a spurious "
        f"n̂ jump > 0.2 (true n=0.4, no long memory at all); got "
        f"n̂1={fit_k1.n}, n̂2={fit_k2.n}"
    )


# ---------------------------------------------------------------------------
# spurious_delta21_null: finite-sample null distribution of Delta21 under a
# TRUE single-exp kernel (no long memory at all), used to calibrate how large
# a real symbol's Delta21 must be before it is more than sampling noise.
# ---------------------------------------------------------------------------


def test_spurious_delta21_null_median_is_positive_at_small_sample():
    """At a modest per-window event count (10k), the K=2 fit's extra
    flexibility should on average absorb some sampling noise into a spurious
    second component even though the truth is exactly K=1 -- documenting the
    upward finite-sample bias `spurious_delta21_null` exists to calibrate
    against. n_sims=3 keeps this within the runtime budget; the median of
    3 draws is noisy but the effect is consistently positive across seeds
    (measured during development: medians of 0.03, 0.01-0.02 across several
    seed choices, never negative or exactly zero)."""
    null = spurious_delta21_null(10_000, mu=0.5, alpha=0.4, beta=2.0, n_sims=3, seed=123)
    assert null.shape == (3,)
    assert np.median(null) > 0.0, (
        f"expected a positive median Delta21 under a true K=1 process at "
        f"n=10k events (finite-sample bias), got median={np.median(null)}, null={null}"
    )


def test_spurious_delta21_null_shrinks_with_sample_size():
    """The finite-sample bias documented above shrinks as the per-window
    event count grows: more events per window pin down the K=1 residuals
    more tightly, leaving less noise for a spurious second component to
    absorb. Same seed reused at both sizes so the comparison isolates the
    sample-size effect from seed variation as much as 3 sims allows."""
    null_small = spurious_delta21_null(10_000, mu=0.5, alpha=0.4, beta=2.0, n_sims=3, seed=123)
    null_large = spurious_delta21_null(40_000, mu=0.5, alpha=0.4, beta=2.0, n_sims=3, seed=123)
    assert np.median(null_large) < np.median(null_small), (
        f"expected the null median to shrink from n=10k to n=40k events/window, "
        f"got median_small={np.median(null_small)} ({null_small}), "
        f"median_large={np.median(null_large)} ({null_large})"
    )


# ---------------------------------------------------------------------------
# Group 7: piecewise-baseline Hawkes control (`fit_hawkes_exp_piecewise_mu`,
# `baseline_drift_control`) -- THE CONTROL described in `fit_hawkes_multiexp`'s
# "THE CONTROL" section: re-fit K=1 with a block-wise constant baseline
# instead of a single constant mu, to test whether a K=1->K=2 rise survives
# once the baseline is allowed to vary, or vanishes (i.e. was baseline drift
# absorbed by a spurious slow kernel component all along).
#
# RESOLUTION: a block-wise baseline can only absorb drift SLOWER than the
# block width t_end/n_blocks. The drift fixture below therefore uses a slow
# baseline (4 levels per 86400 s day, i.e. 21600 s per level) against 5000 s
# blocks. A fast wobble (e.g. the 1200 s-period fixture of
# `test_seasonal_baseline_confound_mimics_long_memory`) averages out inside
# any block the <=12-block cap allows and is NOT resolvable by this control.
# ---------------------------------------------------------------------------


def test_piecewise_mu_loglik_matches_numerical_intensity_integration():
    """Verify the block-wise-baseline log-likelihood formula against
    brute-force numerical integration, mirroring
    `test_loglik_matches_numerical_intensity_integration` for the constant-mu
    case. Uses 10 fixed event times (not simulated) with a 4-block baseline
    over t_end=10 so block boundaries fall at non-trivial points relative to
    the events."""
    times = np.array([1.0, 1.3, 2.1, 2.15, 3.0, 4.4, 4.5, 4.55, 6.0, 8.0])
    t_end = 10.0
    n_blocks = 4
    mus = np.array([0.2, 0.4, 0.1, 0.5])
    alpha, beta = 0.5, 1.5
    block_width = t_end / n_blocks

    ll_closed = hawkes_piecewise_mu_loglik(times, t_end, mus, alpha, beta, n_blocks)

    def mu_of_t(t: float) -> float:
        idx = min(int(t // block_width), n_blocks - 1)
        return float(mus[idx])

    log_sum = 0.0
    for i, ti in enumerate(times):
        prior = times[:i]
        excitation = np.sum(alpha * beta * np.exp(-beta * (ti - prior))) if i > 0 else 0.0
        log_sum += np.log(mu_of_t(ti) + excitation)

    grid = np.linspace(0.0, t_end, 2_000_000)
    excitation_grid = np.zeros_like(grid)
    for ti in times:
        mask = grid > ti
        excitation_grid[mask] += alpha * beta * np.exp(-beta * (grid[mask] - ti))
    mu_grid = mus[np.minimum((grid // block_width).astype(int), n_blocks - 1)]
    lam_grid = mu_grid + excitation_grid
    compensator_numeric = np.trapezoid(lam_grid, grid)

    ll_numeric = log_sum - compensator_numeric
    assert abs(ll_closed - ll_numeric) < 1e-3, (ll_closed, ll_numeric)


