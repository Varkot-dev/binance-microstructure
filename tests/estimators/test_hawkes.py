def test_baseline_drift_control_on_resolvable_drift_is_drift():
    """A single-exponential Hawkes process (n=0.4, beta=2.0, no long memory)
    whose baseline steps between 0.7x and 1.3x every 21600 s (4 levels over a
    86400 s day; `shape = np.tile([0.7, 1.3], 2)`). With n_blocks=12 over
    t_end=60000 s the block width is 5000 s, well below the drift timescale, so
    the block-wise baseline can absorb it. The constant-mu K=1 fit reads
    n ~= 0.46 and K=2 rises far above it with a very slow component on the
    drift; the piecewise fit recovers most of that likelihood and the verdict
    is 'drift'."""
    shape = np.tile([0.7, 1.3], 2)
    t_end = 60_000.0
    times = simulate_seasonal_hawkes_exp(0.5, 0.4, 2.0, t_end, shape, seed=5)

    result = baseline_drift_control(times, t_end, n_blocks=12)

    assert set(result) == {
        "n_k1",
        "n_k2",
        "n_k1_piecewise",
        "slow_beta_k2",
        "dll_pw",
        "dll_k2",
        "dll_threshold",
        "verdict",
    }
    k2_rise = result["n_k2"] - result["n_k1"]
    assert k2_rise > 0.1, f"result={result}"
    assert result["dll_pw"] >= -1e-6, f"nesting violated: {result}"
    assert result["dll_pw"] >= result["dll_threshold"], f"result={result}"
    assert result["verdict"] == "drift", f"result={result}"


def test_baseline_drift_control_on_two_exp_process_is_not_drift():
    """On a stationary 2-exponential process (alpha=(0.25,0.35), beta=(5,0.2),
    true n=0.6, the planted-kernel fixture of
    `test_multiexp_k2_recovers_planted_two_timescale_kernel`) K=1
    underestimates and K=2 recovers the true n. There is no baseline drift, so
    the block-wise baseline must not explain the K=2 gain and the verdict must
    not be 'drift'."""
    mu = 0.5
    alphas = np.array([0.25, 0.35])
    betas = np.array([5.0, 0.2])
    t_end = 48_000.0
    true_n = float(alphas.sum())
    times = simulate_hawkes_multiexp(mu, alphas, betas, t_end, seed=42)

    result = baseline_drift_control(times, t_end, n_blocks=8)

    assert result["n_k1"] < 0.5, f"n_k1={result['n_k1']}"
    assert abs(result["n_k2"] - true_n) < 0.06, f"n_k2={result['n_k2']}, true_n={true_n}"
    assert result["dll_pw"] >= -1e-6, f"nesting violated: {result}"
    assert result["verdict"] != "drift", f"result={result}"
    # Not asserted: verdict == "long_memory_candidate". When K=1 is misspecified
    # (true long memory) the block-level LR statistic is inflated, so
    # "inconclusive" is also possible here; on this fixture it is not called drift.
    assert result["dll_pw"] < 0.5 * result["dll_k2"], f"result={result}"


