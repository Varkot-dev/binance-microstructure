# Group 6: sum-of-exponentials Hawkes kernel (K-sensitivity of n̂).
#
# A K=1 fit on data from a 2-timescale kernel should underestimate the true
# branching ratio, a K=2 fit should recover it, and a K=3 fit
# (over-parameterized) should stay in the right ballpark without blowing up.
# This probes the project's 41/41-symbol exp-MLE vs count-variance
# disagreement.
#
# Caveat tested at the end of this group
# (`test_seasonal_baseline_confound_mimics_long_memory`): the K=1->K=2 n̂ rise
# and slow-component signature used above is not unique to long memory.
# Residual baseline non-stationarity (imperfect deseasonalization, regime
# changes) produces the same signature in a process with no long memory, so
# n̂(K) alone cannot separate the two. See that test and
# `fit_hawkes_multiexp` for the diagnostic (compare the slow component's
# timescale to the deseasonalization bin width / fit-window length) and the
# control (re-fit K=1 with a block-wise-constant baseline).
# ---------------------------------------------------------------------------

# Planted 2-exponential kernel: alpha=(0.25, 0.35) [n=0.6], beta=(5, 0.2)
# (one fast component, timescale 1/5=0.2, and one slow component, timescale
# 1/0.2=5, a 25x separation).
PLANTED_MU = 0.5
PLANTED_ALPHAS = np.array([0.25, 0.35])
PLANTED_BETAS = np.array([5.0, 0.2])
PLANTED_N = float(PLANTED_ALPHAS.sum())  # 0.6
# mean_rate ~ mu/(1-n) = 0.5/0.4 = 1.25/unit time; t_end=48_000 gives ~60k events.
PLANTED_T_END = 48_000.0


def test_multiexp_k1_matches_fit_hawkes_exp():
    """K=1 must reproduce fit_hawkes_exp on the same data.

    With one component the alpha-logit softmax reduces to the logistic map
    fit_hawkes_exp uses, so both optimizers search the same likelihood surface
    and should land on the same optimum.
    """
    times = simulate_hawkes_exp(TRUE_MU, TRUE_ALPHA, TRUE_BETA, T_END, seed=7)
    fit_times = times[times <= FIT_SUBSAMPLE_T]

    single = fit_hawkes_exp(fit_times, FIT_SUBSAMPLE_T)
    multi = fit_hawkes_multiexp(fit_times, FIT_SUBSAMPLE_T, K=1)

    assert multi.K == 1
    assert multi.alphas.shape == (1,)
    assert multi.betas.shape == (1,)
    # The two fits run independent Nelder-Mead searches (different simplex
    # paths and multi-start beta seeds) over the same likelihood, so they agree
    # only up to each optimizer's tol=1e-6 stopping criterion. Measured here:
    # loglik ~1e-7, mu/alpha ~1e-6/1e-7, beta (the flattest direction) ~3e-5.
    # The tolerances (loglik 1e-5, mu/alpha 1e-5, beta 1e-4) leave headroom
    # while still showing the two code paths compute the same thing.
    assert abs(multi.mu - single.mu) < 1e-5, (multi.mu, single.mu)
    assert abs(multi.alphas[0] - single.alpha) < 1e-5, (multi.alphas[0], single.alpha)
    assert abs(multi.betas[0] - single.beta) < 1e-4, (multi.betas[0], single.beta)
    assert abs(multi.n - single.alpha) < 1e-5
    assert abs(multi.loglik - single.loglik) < 1e-5, (multi.loglik, single.loglik)


