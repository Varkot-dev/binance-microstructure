# Group 1: simulate -> fit round trip across 3 seeds.
# ---------------------------------------------------------------------------

TRUE_MU, TRUE_ALPHA, TRUE_BETA = 0.5, 0.4, 2.0
T_END = 200_000.0
FIT_SUBSAMPLE_T = 100_000.0  # fit on the first 100k seconds of events


def _simulate_and_fit(seed: int) -> tuple[np.ndarray, HawkesFit]:
    times = simulate_hawkes_exp(TRUE_MU, TRUE_ALPHA, TRUE_BETA, T_END, seed=seed)
    # Fit on the first FIT_SUBSAMPLE_T seconds only: full sims are 150-300k
    # events, and fitting about half keeps the suite fast at a realistic size.
    fit_times = times[times <= FIT_SUBSAMPLE_T]
    fit = fit_hawkes_exp(fit_times, FIT_SUBSAMPLE_T)
    return times, fit


@pytest.mark.parametrize("seed", [7, 8, 9])
def test_mle_recovers_known_parameters(seed):
    _, fit = _simulate_and_fit(seed)
    assert fit.converged
    assert abs(fit.alpha - TRUE_ALPHA) < 0.03, f"seed={seed} alpha={fit.alpha}"
    assert abs(fit.mu - TRUE_MU) < 0.05, f"seed={seed} mu={fit.mu}"
    assert abs(fit.beta - TRUE_BETA) / TRUE_BETA < 0.20, f"seed={seed} beta={fit.beta}"


def test_mle_alpha_stable_across_seeds():
    alphas = []
    for seed in (7, 8, 9):
        _, fit = _simulate_and_fit(seed)
        alphas.append(fit.alpha)
    sd = float(np.std(alphas, ddof=1))
    assert sd < 0.02, f"alphas={alphas} sd={sd}"


