def test_seasonal_baseline_confound_mimics_long_memory():
    """Baseline non-stationarity mimics long memory in the K=1 -> K=2 sweep.

    A K=1 -> K=2 rise in n̂ with a slow (small beta) second component is also
    produced by residual baseline non-stationarity that a constant-mu fit
    cannot represent (the Filimonov & Sornette 2015 trap, see
    `test_regime_switching_poisson_produces_spurious_endogeneity_trap`). This
    shows the same confound fools the multi-exponential MLE.

    Ground truth is a single-exponential Hawkes process (n=0.4, beta=2.0, no
    long memory) with a piecewise-constant ±30% baseline wobble:
    `np.tile([0.7, 1.3], 72)` divides the 86400s day into 144 bins of 600s in
    `simulate_seasonal_hawkes_exp`'s convention, and t_end=60_000s covers a bit
    over half a period. K=1 -> K=2 shows n̂1=0.46 -> n̂2=0.83 (a jump above
    0.2) with a spurious near-zero beta component, the same shape as the
    long-memory signature in
    `test_multiexp_k1_underestimates_planted_two_timescale_kernel` and
    `test_multiexp_k2_recovers_planted_two_timescale_kernel`. So n̂(K)
    sensitivity alone cannot separate long memory from a non-constant
    baseline; per `fit_hawkes_multiexp`, that takes (a) comparing the slow
    component's timescale 1/beta_slow with the deseasonalization bin width and
    fit-window length, and (b) the block-wise-constant-mu control.
    """
    shape = np.tile([0.7, 1.3], 72)
    t_end = 60_000.0
    times = simulate_seasonal_hawkes_exp(0.5, 0.4, 2.0, t_end, shape, seed=5)

    fit_k1 = fit_hawkes_multiexp(times, t_end, K=1)
    fit_k2 = fit_hawkes_multiexp(times, t_end, K=2)

    assert fit_k2.n - fit_k1.n > 0.2, (
        f"expected the baseline-drift confound to produce a spurious "
        f"n̂ jump > 0.2 (true n=0.4, no long memory at all); got "
        f"n̂1={fit_k1.n}, n̂2={fit_k2.n}"
    )


